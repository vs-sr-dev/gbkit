"""Recompile a Game Boy cartridge to C++ and build it with the runtime.

    python -m gbkit.recomp ROM.gb --trace build/trace/KEY --out build/recomp/KEY [--build]
                                  [-O g|1|2] [--history] [--no-comments]

The regions (recomp/discover.py) become C++ (recomp/emit.py), a few regions a
file so the build runs in parallel; `gb_register_all` registers every
function at every way in.  --build compiles them against the runtime
(runtime/, built once and shared) to OUT/gb.exe -- msys2's ucrt64 g++, SDL2
for --window when it is there.
"""
import argparse
import os
import sys

from .. import cart as cartmod
from . import discover, emit
from .build import build

LINES_PER_FILE = 40000


def generate(rom, trace, out, comments=True, log=print):
    c = cartmod.Cart.load(rom)
    tr = discover.Trace(trace, c) if trace else None
    p = discover.Program(c, tr).discover()
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        if f.startswith('gen_') and f.endswith('.cpp'):
            os.remove(os.path.join(out, f))
    files, cur, n, funcs, sites = [], [], 0, [], {}

    def flush():
        nonlocal cur, n
        if not cur:
            return
        path = os.path.join(out, f'gen_{len(files):03d}.cpp')
        with open(path, 'w', encoding='utf8', newline='\n') as f:
            f.write('// generated by gbkit.recomp: do not edit\n#include "gb.h"\n\n')
            f.write('\n'.join(cur))
            f.write('\n')
        files.append(path)
        cur, n = [], 0
    for k in sorted(p.regions):
        r = p.regions[k]
        e = emit.Emitter(p, r, comments)
        lines = e.emit()
        protos = [f'void {name}(GB& c, uint16_t e);' for name, _ in e.funcs]
        cur += protos + [''] + lines
        n += len(lines)
        for name, ways in e.funcs:
            funcs.append((r, name, ways))
        for kk, v in e.sites.items():
            sites[kk] = sites.get(kk, 0) + v
        if n >= LINES_PER_FILE:
            flush()
    flush()
    path = os.path.join(out, 'gen_register.cpp')
    with open(path, 'w', encoding='utf8', newline='\n') as f:
        f.write('// generated by gbkit.recomp: do not edit\n#include "gb.h"\n\n')
        for r, name, ways in funcs:
            f.write(f'void {name}(GB& c, uint16_t e);\n')
        f.write('\nvoid gb_register_all() {\n')
        for r, name, ways in funcs:
            for w in ways:
                f.write(f'    gb_register({r.win}, 0x{r.bank:03X}, 0x{w:04X}, {name});\n')
        f.write('}\n')
    files.append(path)
    insns = sum(len(r.code) for r in p.regions.values())
    cov = p.coverage()
    log(f'{c.key}: {len(p.regions)} regions, {len(funcs)} functions, {insns} instructions'
        + (f', traced code held {cov[0]}/{cov[1]}' if cov else '')
        + '  ' + ' '.join(f'{k}:{v}' for k, v in sorted(sites.items())))
    return files, p


def main(argv=None):
    ap = argparse.ArgumentParser(prog='gbkit.recomp')
    ap.add_argument('rom')
    ap.add_argument('--trace')
    ap.add_argument('--out', required=True)
    ap.add_argument('--build', action='store_true')
    ap.add_argument('--no-comments', action='store_true')
    ap.add_argument('-O', dest='opt', default='g')
    ap.add_argument('--history', action='store_true', help='record the last instructions (debugging)')
    a = ap.parse_args(argv)
    files, _ = generate(a.rom, a.trace, a.out, not a.no_comments)
    if a.build:
        build(a.out, files, opt='-O' + a.opt, history=a.history)
    return 0


if __name__ == '__main__':
    sys.exit(main())
